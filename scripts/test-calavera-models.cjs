const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {createRequire} = require('node:module');
const puppeteer = createRequire('D:/CLAUDE CODE/video-tools/boomart-videos/package.json')('puppeteer-core');
const base = process.env.BOOMART_TEST_BASE_URL || 'http://127.0.0.1:4183';
const products = JSON.parse(fs.readFileSync('data/products.json','utf8'));
const memory = new Map([['boomart_cart_v1', JSON.stringify([{productId:'mascara-calavera',variant:'nino',quantity:1}])]]);
// Precio, separación de modelos e imagen a través del carrito real, sin datos de clientes.
const context={window:{},document:{dispatchEvent(){},addEventListener(){}},CustomEvent:class{},fetch:async()=>({json:async()=>products}),localStorage:{getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)},console};
context.window=context;
context.BOOMART_PRODUCTS=products;
vm.runInNewContext(fs.readFileSync('src/cart.js','utf8'),context);
(async()=>{
  await new Promise(resolve=>setImmediate(resolve));
  const cart=context.BoomartCart;
  assert.equal(cart.getState().lines[0].unitPrice,90);
  cart.clear();
  cart.add('mascara-calavera','adulto',1);
  cart.add('mascara-calavera','con-cuernos:adulto',1);
  cart.add('mascara-calavera','con-cuernos:nino',1);
  const lines=cart.getState().lines;
  assert.equal(lines.length,3);
  assert.equal(lines.find(x=>x.variantKey==='clasica:adulto').unitPrice,100);
  assert.equal(lines.find(x=>x.variantKey==='con-cuernos:adulto').unitPrice,150);
  assert.equal(lines.find(x=>x.variantKey==='con-cuernos:nino').unitPrice,135);
  assert.match(lines.find(x=>x.variantKey==='con-cuernos:adulto').image,/con-cuernos/);
  const browser=await puppeteer.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--no-sandbox']});
  try {
    const page=await browser.newPage();
    await page.setViewport({width:390,height:844});
    await page.setRequestInterception(true);
    page.on('request',request=>request.url().startsWith(base)||request.url().startsWith('data:')?request.continue():request.abort());
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(base+'/producto/mascara-calavera/?modelo=con-cuernos',{waitUntil:'networkidle0'});
    assert.match(await page.$eval('#ppMain',el=>el.src),/con-cuernos-0.webp/);
    assert.equal(await page.$$eval('#ppThumbs button',els=>els.length),4);
    assert.match(await page.$eval('#ppShop',el=>el.href),/modelo=con-cuernos/);
    assert.match(decodeURIComponent(await page.$eval('#ppWhatsapp',el=>el.href)),/con cuernos.*S\/150/);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:'calavera-modelo-mobile.png',fullPage:false});
    await page.click('[data-pp-model="clasica"]');
    assert.match(await page.$eval('#ppMain',el=>el.src),/mascara-calavera-0.webp/);
    assert.equal(await page.$$eval('#ppThumbs button',els=>els.length),6);
    await page.goto(base+'/index.html?producto=mascara-calavera&modelo=con-cuernos',{waitUntil:'networkidle0'});
    await page.waitForSelector('#productModal[open]');
    assert.match(await page.$eval('#modalTitle',el=>el.textContent),/con cuernos/);
    assert.match(await page.$eval('#modalImageWrap img',el=>el.src),/con-cuernos/);
    assert.match(await page.$eval('#modalPricing [data-variant-option$=":adulto"] strong',el=>el.textContent),/150/);
    await page.click('#modalPricing [data-variant-option="con-cuernos:nino"]');
    await page.click('#modalPricing [data-model-option="clasica"]');
    assert.equal(await page.$eval('#modalPricing .add-to-cart',el=>el.dataset.variant),'clasica:nino');
    assert.match(await page.$eval('#modalPricing [data-variant-option="clasica:nino"] strong',el=>el.textContent),/90/);
    await page.click('#modalPricing [data-model-option="con-cuernos"]');
    assert.match(await page.$eval('#modalPricing [data-variant-option="con-cuernos:nino"] strong',el=>el.textContent),/135/);
    await page.click('#modalPricing [data-variant-option="con-cuernos:adulto"]');
    await page.click('#modalPricing [data-add-to-cart]');
    const actual=await page.evaluate(()=>window.BoomartCart.getState().lines);
    assert.equal(actual[0].variantKey,'con-cuernos:adulto');
    assert.equal(actual[0].unitPrice,150);
    assert.match(actual[0].image,/con-cuernos/);
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('OK: modelos, precios, carrito compatible, galerías, enlace directo, WhatsApp y móvil.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
